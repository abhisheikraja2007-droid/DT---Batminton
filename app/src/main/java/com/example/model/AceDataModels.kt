  val id: String,
  val title: String,
  val dateFormatted: String,
  val durationMinutes: Int,
  val totalReps: Int,
  val avgFormScore: Int,
  val peakSpeedKmH: Int,
  val grade: String,
  val sweetSpotPct: Int,
  val keyTakeaway: String
