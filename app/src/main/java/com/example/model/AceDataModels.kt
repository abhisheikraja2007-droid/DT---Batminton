data class SkillRadarDimension(
  val name: String,
  val score: Int,
  val benchmark: Int = 85,
  val metricLabel: String,
  val deltaString: String
)

data class WeeklyProgressionPoint(
  val label: String,
  val formScore: Int,
  val peakSpeedKmH: Int,
  val accuracyPct: Int
)

